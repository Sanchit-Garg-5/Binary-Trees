class Node{
    public:
    ll data;
    Node* left; 
    Node* right;
    Node(ll val, Node* left1, Node* right1):data(val),left(left1),right(right1){}
    Node(ll val):data(val),left(nullptr),right(nullptr){}
    Node():data(0),left(nullptr),right(nullptr){}
};

// tc is o(n) 
//sc is o(h) (recursive) and o(n) (worst for skewed/linked list type bt)
bool check(Node* curr,Node* p,Node* q,Node*& ans, bool& done){
    if(done || !curr){return false;}
    //done==true or curr==null means simply return
    if(curr==p || curr==q){//check by nodes,not values(duplicates)
        ans=curr; // let us say p is ancestor of q, then clearly no need to explore 
        //below p. and p can be the answer-so save it.
        //but this doesnt mean that always p is the answer-just because we found p. 
        //what is p is not ancestor of q is the case. so save p as a provisional answer.
        return true;
    }
    bool left=check(curr->left,p,q,ans,done),right=check(curr->right,p,q,ans,done);
    if(left && right){done=true; ans=curr; return false;}
    //if p exists in left and q in right, then i am the answer,set done=true
    //and return false
    //only when left,right both return true;that means i am the ans
    return left||right;
    //if even anyone left,right is false:that means i can't be the answer.
}
int main(){
    Node* root=new Node(5);
    root->left=new Node(6);
    root->right=new Node(7);
    root->left->left=new Node(8);
    root->left->right=new Node(9);
    root->left->right->left=new Node(1);
    //p and q are the nodes to be searched for
    Node*ans=nullptr; //if either or both p and q don't exist in the bt
    bool done=false;
    if(root){check(root,p,q,ans,done);}
}
