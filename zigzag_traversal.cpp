class Node{
    public:
    ll data;
    Node* left; 
    Node* right;
    Node(ll val, Node* left1, Node* right1):data(val),left(left1),right(right1){}
    Node(ll val):data(val),left(nullptr),right(nullptr){}
    Node():data(0),left(nullptr),right(nullptr){}
};


int main(){
    Node* root=new Node(5);
    root->left=new Node(6);
    root->right=new Node(7);
    root->left->left=new Node(8);
    root->left->right=new Node(9);
    root->left->right->left=new Node(1);
    queue<Node*>me;
    //TC is O(3n-4n). 
    // SC is O(w) for the queue and the level vector, plus the O(n) output in ans.
    //we always add left to right in the queue
    //but place them accordingly to where they belong in temp vector
    //depending upon if its odd or even level
    //and then add temp to the ans 2d vector
    vector<vector<ll>>ans; ll num=1;
    if(root){me.push(root);}
    while(!me.empty()){
        ll n=me.size(); vector<ll>temp(n);
        ll i=0;
        while(i<n){
            Node* ntemp=me.front();
            if(num==1){temp[i]=ntemp->data;}
            else{temp[n-i-1]=ntemp->data;}
            if(ntemp->left){me.push(ntemp->left);}
            if(ntemp->right){me.push(ntemp->right);}
            me.pop();
            i++;
        }
        ans.push_back(temp);
        if(num){num=0;} else{num=1;}
    }
}
