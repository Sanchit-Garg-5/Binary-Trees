class Node{
    public:
    ll data;
    Node* left; 
    Node* right;
    Node(ll val, Node* left1, Node* right1):data(val),left(left1),right(right1){}
    Node(ll val):data(val),left(nullptr),right(nullptr){}
    Node():data(0),left(nullptr),right(nullptr){}
};
// tc is o(n) not o(2n) as nodes dont get explored twice. 
//sc is o(h) (recursive) and o(n) (worst for skewed/linked list type bt)
bool check(Node* curr1,Node* curr2){
    if(!curr1 && !curr2){return true;}
    if(!curr1 || !curr2){return false;}
    if(curr1->val!=curr2->val){return false;}
    return (check(curr1->left,curr2->right) && check(curr1->right, curr2->left));
}
